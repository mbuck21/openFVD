static float fromBits(uint32_t u) { float f; memcpy(&f, &u, 4); return f; }
static uint32_t toBits(float f) { uint32_t u; memcpy(&u, &f, 4); return u; }

static int failures = 0;

template <size_t N>
static void checkAll(const char* name, float (*fn)(float), const uint32_t (&cases)[N][2])
{
    int bad = 0;
    for (size_t i = 0; i < N; ++i) {
        const float x = fromBits(cases[i][0]);
        const float want = fromBits(cases[i][1]);
        const float got = fn(x);
        const bool same = toBits(got) == toBits(want) || (std::isnan(got) && std::isnan(want));
        if (!same) {
            printf("FAIL  %s(%a) gave %a, the 2016 binary gave %a\n", name, x, got, want);
            ++bad;
        }
    }
    printf("%s  %s: %d of %d arguments give the 2016 binary's exact result\n",
           bad ? "FAIL" : "ok  ", name, (int)N - bad, (int)N);
    failures += bad;
}

